import json
import logging
from typing import Dict, Any, List, Optional
import google.generativeai as genai
from app.core.config import settings

logger = logging.getLogger(__name__)

# Configure Gemini
if settings.GEMINI_API_KEY:
    genai.configure(api_key=settings.GEMINI_API_KEY)

def get_gemini_model():
    return genai.GenerativeModel(settings.GEMINI_MODEL_NAME)

RESUME_EXTRACTION_PROMPT = """
You are an expert AI Resume Parsing Engine for an engineering student career guidance platform.
Analyze the following extracted resume text carefully and output ONLY a valid JSON object matching the exact schema specified below.

Schema:
{
  "name": "Full name of candidate or null",
  "email": "Email address or null",
  "phone": "Phone number or null",
  "github_url": "GitHub URL or null",
  "linkedin_url": "LinkedIn URL or null",
  "college_name": "University/College name or null",
  "branch": "Degree and branch (e.g. Computer Science and Engineering) or null",
  "cgpa": 8.5 (float out of 10.0, or convert percentage/GPA to 10 scale, or null),
  "skills": ["python", "pytorch", "fastapi", "docker"] (array of lowercase technical skills, programming languages, frameworks, tools, databases),
  "projects": [
    {
      "id": "proj_1",
      "title": "Project Title",
      "description": "Brief summary of what was built and impact",
      "tech_stack": ["Python", "FastAPI"],
      "github_url": "GitHub URL or null",
      "live_demo_url": null
    }
  ],
  "internships": [
    {
      "id": "intern_1",
      "company_name": "Company Name",
      "domain": "Domain or industry e.g. AI / ML",
      "role": "Title e.g. Software Engineering Intern",
      "start_date": "YYYY-MM or string",
      "end_date": "YYYY-MM or string or Present",
      "is_current": false,
      "description": "Summary of responsibilities"
    }
  ],
  "certifications": [
    "AWS Certified Cloud Practitioner",
    "Certification Title"
  ]
}

Strict Rules:
- Return ONLY valid raw JSON without markdown code fences or backticks.
- Normalize technical skills to clean strings (e.g., 'python', 'react', 'fastapi', 'postgresql', 'docker').
- If a value cannot be found in the resume, set it to null or an empty list.

Resume Text:
"""

def extract_resume_details(raw_text: str) -> Dict[str, Any]:
    """
    Extracts structured profile data from raw resume text using Gemini.
    """
    try:
        model = get_gemini_model()
        prompt = RESUME_EXTRACTION_PROMPT + raw_text[:12000]  # truncate to prevent context blowout
        response = model.generate_content(
            prompt,
            generation_config={"response_mime_type": "application/json"}
        )
        text = response.text.strip()
        # Clean potential markdown fences if present
        if text.startswith("```json"):
            text = text[7:]
        if text.startswith("```"):
            text = text[3:]
        if text.endswith("```"):
            text = text[:-3]
        return json.loads(text.strip())
    except Exception as e:
        logger.error(f"Gemini resume extraction failed: {e}")
        # Fallback empty extraction if LLM fails
        return {
            "name": None,
            "email": None,
            "phone": None,
            "github_url": None,
            "linkedin_url": None,
            "college_name": None,
            "branch": None,
            "cgpa": None,
            "skills": [],
            "projects": [],
            "internships": [],
            "certifications": [],
            "parsing_warning": str(e)
        }

INSIGHTS_PROMPT = """
You are a senior tech career mentor for engineering students.
Based on the student's profile and the top predictions generated by our PyTorch Career Recommendation model, generate:
1. A concise, encouraging, and specific 2-sentence career alignment insight ("top_insight").
2. Estimated skill radar proficiency scores from 0 to 100 for these 5 pillars:
   - "Core Programming"
   - "Framework Mastery"
   - "System & Cloud"
   - "Data & Mathematics"
   - "Engineering Practices"

Output ONLY a valid JSON object matching:
{
  "top_insight": "Insight text here...",
  "skill_radar": {
    "Core Programming": 85,
    "Framework Mastery": 80,
    "System & Cloud": 65,
    "Data & Mathematics": 78,
    "Engineering Practices": 70
  }
}
"""

def generate_career_insights(profile_text: str, top_predictions: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Generates actionable career insight and skill radar using Gemini.
    """
    try:
        model = get_gemini_model()
        payload = {
            "profile_text": profile_text,
            "top_predictions": top_predictions[:3],
        }
        prompt = INSIGHTS_PROMPT + "\n\nStudent Data:\n" + json.dumps(payload, indent=2)
        response = model.generate_content(
            prompt,
            generation_config={"response_mime_type": "application/json"}
        )
        text = response.text.strip()
        if text.startswith("```json"):
            text = text[7:]
        if text.startswith("```"):
            text = text[3:]
        if text.endswith("```"):
            text = text[:-3]
        return json.loads(text.strip())
    except Exception as e:
        logger.warning(f"Gemini insights generation fallback used: {e}")
        top_role = top_predictions[0]["label"] if top_predictions else "Software Engineer"
        return {
            "top_insight": f"Strong alignment with {top_role}. Your combination of technical projects and coursework positions you well for roles in this domain.",
            "skill_radar": {
                "Core Programming": 75,
                "Framework Mastery": 70,
                "System & Cloud": 60,
                "Data & Mathematics": 65,
                "Engineering Practices": 68
            }
        }
